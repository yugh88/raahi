#!/usr/bin/env python3
"""Convert SVG <symbol>s (and standalone SVG files) into Android VectorDrawable XML.

Supports the subset used by Raahi's artwork: path, circle, ellipse, rect (with rx), and the
fill / stroke / stroke-width / stroke-linecap / stroke-linejoin / opacity attributes, with
inheritance from the <symbol> or <svg> element. "currentColor" becomes opaque black so the
icon can be tinted from Compose.

Usage:
  svg2vector.py symbols <file-with-symbols> <out-dir> [--prefix ic_] [--only id,id]
  svg2vector.py file <file.svg> <out.xml>
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

SVG_NS = "{http://www.w3.org/2000/svg}"
INHERITED = ("fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin")


def color(value):
    if value in (None, "none"):
        return None
    if value == "currentColor":
        return "#FF000000"
    value = value.strip()
    if re.fullmatch(r"#[0-9a-fA-F]{3}", value):
        value = "#" + "".join(c * 2 for c in value[1:])
    if re.fullmatch(r"#[0-9a-fA-F]{6}", value):
        return "#FF" + value[1:].upper()
    raise ValueError(f"unsupported colour {value!r}")


def num(v):
    return float(v) if v is not None else 0.0


def fmt(x):
    return ("%.3f" % x).rstrip("0").rstrip(".")


def shape_to_path(el):
    tag = el.tag.replace(SVG_NS, "")
    if tag == "path":
        return el.get("d")
    if tag in ("circle", "ellipse"):
        cx, cy = num(el.get("cx")), num(el.get("cy"))
        rx = num(el.get("r") or el.get("rx"))
        ry = num(el.get("r") or el.get("ry"))
        return (f"M{fmt(cx - rx)},{fmt(cy)}a{fmt(rx)},{fmt(ry)} 0 1,0 {fmt(2 * rx)},0"
                f"a{fmt(rx)},{fmt(ry)} 0 1,0 {fmt(-2 * rx)},0Z")
    if tag == "rect":
        x, y = num(el.get("x")), num(el.get("y"))
        w, h = num(el.get("width")), num(el.get("height"))
        r = min(num(el.get("rx") or el.get("ry")), w / 2, h / 2)
        if r == 0:
            return f"M{fmt(x)},{fmt(y)}h{fmt(w)}v{fmt(h)}h{fmt(-w)}Z"
        return (f"M{fmt(x + r)},{fmt(y)}h{fmt(w - 2 * r)}a{fmt(r)},{fmt(r)} 0 0,1 {fmt(r)},{fmt(r)}"
                f"v{fmt(h - 2 * r)}a{fmt(r)},{fmt(r)} 0 0,1 {fmt(-r)},{fmt(r)}"
                f"h{fmt(-(w - 2 * r))}a{fmt(r)},{fmt(r)} 0 0,1 {fmt(-r)},{fmt(-r)}"
                f"v{fmt(-(h - 2 * r))}a{fmt(r)},{fmt(r)} 0 0,1 {fmt(r)},{fmt(-r)}Z")
    return None


def convert(root, width_dp=None):
    vb = [float(v) for v in root.get("viewBox").split()]
    vw, vh = vb[2], vb[3]
    defaults = {"fill": "#000000"}
    defaults.update({k: root.get(k) for k in INHERITED if root.get(k) is not None})
    w = width_dp or vw
    h = w * vh / vw
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Generated by tools/svg2vector.py; edit the SVG source, not this file. -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           f'    android:width="{fmt(w)}dp"', f'    android:height="{fmt(h)}dp"',
           f'    android:viewportWidth="{fmt(vw)}"', f'    android:viewportHeight="{fmt(vh)}">']
    for el in root.iter():
        if el is root:
            continue
        d = shape_to_path(el)
        if d is None:
            continue
        attrs = dict(defaults)
        attrs.update({k: el.get(k) for k in INHERITED if el.get(k) is not None})
        line = [f'    <path android:pathData="{d}"']
        fill = color(attrs.get("fill"))
        stroke = color(attrs.get("stroke"))
        if fill:
            line.append(f'        android:fillColor="{fill}"')
        if stroke:
            line.append(f'        android:strokeColor="{stroke}"')
            line.append(f'        android:strokeWidth="{attrs.get("stroke-width", "1")}"')
            if attrs.get("stroke-linecap"):
                line.append(f'        android:strokeLineCap="{attrs["stroke-linecap"]}"')
            if attrs.get("stroke-linejoin"):
                line.append(f'        android:strokeLineJoin="{attrs["stroke-linejoin"]}"')
        if el.get("opacity"):
            line.append(f'        android:fillAlpha="{el.get("opacity")}"')
            if stroke:
                line.append(f'        android:strokeAlpha="{el.get("opacity")}"')
        out.append("\n".join(line) + " />")
    out.append("</vector>\n")
    return "\n".join(out)


def symbols(src, out_dir, prefix, only):
    text = Path(src).read_text(encoding="utf-8")
    count = 0
    for m in re.finditer(r"<symbol\b[^>]*>.*?</symbol>", text, re.S):
        el = ET.fromstring(m.group(0).replace("<symbol", '<symbol xmlns="http://www.w3.org/2000/svg"', 1))
        sid = el.get("id")
        if only and sid not in only:
            continue
        name = prefix + re.sub(r"^i-", "", sid).replace("-", "_")
        width = 24 if el.get("viewBox") == "0 0 24 24" else None
        Path(out_dir, name + ".xml").write_text(convert(el, width), encoding="utf-8")
        count += 1
    print(f"{src}: {count} vectors")


def main(argv):
    if argv[1] == "file":
        Path(argv[3]).write_text(convert(ET.parse(argv[2]).getroot()), encoding="utf-8")
    elif argv[1] == "symbols":
        prefix, only = "ic_", None
        if "--prefix" in argv:
            prefix = argv[argv.index("--prefix") + 1]
        if "--only" in argv:
            only = set(argv[argv.index("--only") + 1].split(","))
        symbols(argv[2], argv[3], prefix, only)


if __name__ == "__main__":
    main(sys.argv)
