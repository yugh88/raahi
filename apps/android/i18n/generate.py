#!/usr/bin/env python3
"""Generate Android string resources from the i18n TSV files.

Each `<module>.tsv` (e.g. `feature-home.tsv` → :feature:home) has the header
    key  en  hi  ta  te  kn  ml
`en` goes to values/ (English base, also used for every English sublabel); the other columns
go to values-<lang>/. A row whose language columns are all empty is English-only and is
written with translatable="false". Lines starting with # are comments.

Usage: generate.py            write files
       generate.py --check    exit 1 if any generated file is out of date (CI)
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LANGS = ["hi", "ta", "te", "kn", "ml"]
HEADER = ["key", "en"] + LANGS


def escape(text: str) -> str:
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("'", "\\'").replace('"', '\\"')
    if text[:1] in ("@", "?"):
        text = "\\" + text
    return text


def read(tsv: Path):
    rows = []
    with tsv.open(encoding="utf-8", newline="") as f:
        lines = [l for l in f if l.strip() and not l.startswith("#")]
    reader = csv.reader(lines, delimiter="\t", quoting=csv.QUOTE_NONE)
    header = next(reader)
    if header != HEADER:
        sys.exit(f"{tsv.name}: header must be {HEADER}, got {header}")
    seen = set()
    for n, row in enumerate(reader, start=2):
        row += [""] * (len(HEADER) - len(row))
        key = row[0].strip()
        if key in seen:
            sys.exit(f"{tsv.name}:{n}: duplicate key {key}")
        seen.add(key)
        if not row[1]:
            sys.exit(f"{tsv.name}:{n}: {key} has no English text")
        rows.append(dict(zip(HEADER, row)))
    return rows


def render(rows, lang):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           "<!-- Generated by i18n/generate.py from i18n/*.tsv. Do not edit by hand. -->",
           "<resources>"]
    for r in rows:
        english_only = not any(r[l] for l in LANGS)
        if lang == "en":
            attr = ' translatable="false"' if english_only else ""
            out.append(f'    <string name="{r["key"]}"{attr}>{escape(r["en"])}</string>')
        elif r[lang]:
            out.append(f'    <string name="{r["key"]}">{escape(r[lang])}</string>')
        elif not english_only:
            sys.exit(f'{r["key"]}: missing {lang} translation')
    out.append("</resources>\n")
    return "\n".join(out)


def main():
    check = "--check" in sys.argv
    stale = []
    for tsv in sorted(Path(__file__).parent.glob("*.tsv")):
        module = ROOT.joinpath(*tsv.stem.split("-"))
        rows = read(tsv)
        for lang in ["en"] + LANGS:
            folder = "values" if lang == "en" else f"values-{lang}"
            target = module / "src/main/res" / folder / "strings.xml"
            text = render(rows, lang)
            if check:
                if not target.exists() or target.read_text(encoding="utf-8") != text:
                    stale.append(str(target.relative_to(ROOT)))
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(text, encoding="utf-8")
    if stale:
        print("Out of date (run i18n/generate.py):\n  " + "\n  ".join(stale))
        sys.exit(1)


if __name__ == "__main__":
    main()
